import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { createServer } from "node:http";
import { build } from "esbuild";
import puppeteer from "puppeteer-core";
const bundle = await build({ entryPoints: ["tests/fixtures/chat-width.tsx"], bundle: true, write: false, outdir: "/tmp/lh-width-bundle", format: "iife", define: { "process.env.NODE_ENV": '"production"' } });
const server = createServer((req, res) => {
 res.setHeader("Content-Type", req.url === "/app.js" ? "text/javascript" : req.url === "/app.css" ? "text/css" : "text/html");
 res.end(req.url === "/app.js" ? bundle.outputFiles.find(f => f.path.endsWith(".js"))!.text : req.url === "/app.css" ? bundle.outputFiles.find(f => f.path.endsWith(".css"))!.text : '<html><style>body{margin:0;--muted-foreground:#555}</style><link rel="stylesheet" href="/app.css"><div id="root"></div><script src="/app.js"></script></html>');
});
await new Promise<void>(r => server.listen(0, "127.0.0.1", r));
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
try {
 const page = await browser.newPage();
 await page.evaluateOnNewDocument("window.__name = fn => fn");
 await page.setViewport({ width: 1440, height: 900 });
 await page.goto(`http://127.0.0.1:${(server.address() as { port: number }).port}`);
 await page.waitForSelector('[role="separator"]');
 const geometry = () => page.evaluate(() => {
  const box = (s: string) => { const b = document.querySelector(s)!.getBoundingClientRect(); return { x: b.x, width: b.width }; };
  return { feed: box("#feed"), dock: box("#dock"), scope: box("#scope"), iframe: box("iframe") };
 });
 const initial = await geometry();
 assert.equal(initial.feed.width, 1200);
 assert.equal(initial.iframe.x - initial.feed.x, 24);
 const handles = await page.$$eval('[role="separator"]', elements => elements.map(e => {
  const hit = e.getBoundingClientRect();
  const line = e.querySelector('span')!.getBoundingClientRect();
  return { width: hit.width, lineLeft: line.left, lineRight: line.right };
 }));
 assert(handles.every(h => h.width >= 24), "hover target fills the message gutter");
 assert(handles[0]!.lineLeft >= initial.feed.x + 8, "left line stays inside the window edge");
 assert(handles[1]!.lineRight <= initial.feed.x + initial.feed.width - 8, "right line stays inside the window edge");
 const opacity = () => page.$eval('[role="separator"] span', e => getComputedStyle(e).opacity);
 assert.equal(await opacity(), "0");
 await page.mouse.move(260, 200);
 await new Promise(r => setTimeout(r, 200));
 assert(Number(await opacity()) >= 0.65, "hover line is clearly visible");
 await page.mouse.down(); await page.mouse.move(460, 200, { steps: 20 }); await page.mouse.up();
 const left = await geometry();
 assert.equal(left.feed.width, 800);
 assert.equal(left.feed.x, 440);
 assert.deepEqual(left.dock, initial.dock);
 await mkdir("work/chat-width", { recursive: true });
 await page.screenshot({ path: "work/chat-width/wide.png" });
 await page.reload(); await page.waitForSelector('[role="separator"]');
 assert.equal((await geometry()).feed.width, 800);
 await page.mouse.move(1234, 200); await page.mouse.down(); await page.mouse.move(1134, 200, { steps: 10 }); await page.mouse.up();
 assert.equal((await geometry()).feed.width, 600);
 await page.focus('[data-side="right"]'); await page.keyboard.press("Home");
 assert.equal((await geometry()).feed.width, 480);
 await page.keyboard.press("ArrowRight"); assert.equal((await geometry()).feed.width, 496);
 await page.click("#sidebar");
 assert.equal((await geometry()).feed.width, 496);
 assert.equal((await geometry()).feed.x, (1440 - 496) / 2);
 await page.setViewport({ width: 390, height: 900 });
 await new Promise(r => setTimeout(r, 100));
 assert.equal((await geometry()).feed.width, 390);
 assert.equal(await page.$eval('[role="separator"]', e => e.getClientRects().length), 0);
 await page.setViewport({ width: 1440, height: 900 }); await new Promise(r => setTimeout(r, 100));
 assert.equal((await geometry()).feed.width, 496);
 await page.focus('[data-side="right"]'); await page.keyboard.press("End");
 assert.equal((await geometry()).feed.width, 1440);
 await page.focus('[data-side="right"]'); await page.keyboard.press("Home");
 await page.click("#rails");
 assert.equal((await geometry()).feed.width, 1440, "unmount must restore feed style");
 await page.click("#rails");
 assert.equal((await geometry()).feed.width, 480, "remount must restore persisted width");
 const cancelHandle = await (await page.$('[data-side="right"]'))!.boundingBox();
 assert(cancelHandle);
 await page.mouse.move(cancelHandle.x + cancelHandle.width / 2, cancelHandle.y + 100); await page.mouse.down();
 await page.$eval('[data-side="right"]', el => el.dispatchEvent(new PointerEvent("pointercancel", { bubbles: true, pointerId: 1 })));
 await page.mouse.up();
 assert.equal(await page.$('.chat-width-shield'), null, "pointer cancel releases iframe shield");
 await page.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "reduce" }]);
 assert.equal(await page.$eval('[role="separator"] span', e => getComputedStyle(e).transitionDuration), "0s");
 console.log("PASS: symmetric rails, hover, iframe crossing, keyboard, clamp, persistence, sidebar, mobile, dock, reduced motion");
} finally { await browser.close(); server.close(); }
